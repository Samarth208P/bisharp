import { readFile, writeFile, mkdir } from "node:fs/promises";
await mkdir("src/lib", { recursive: true });
const { abi } = JSON.parse(
  await readFile("out/Bisharp.sol/Bisharp.json", "utf8"),
);
await writeFile(
  "src/lib/abi.ts",
  `// Generated by npm run abi after forge build.\nexport const escrowAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log("Exported Bisharp ABI to src/lib/abi.ts");
const source = JSON.parse(
  await readFile("out/SourceEscrow.sol/SourceEscrow.json", "utf8"),
);
const destination = JSON.parse(
  await readFile(
    "out/DestinationExecutor.sol/DestinationExecutor.json",
    "utf8",
  ),
);
await writeFile(
  "src/lib/cross-abi.ts",
  `// Generated by npm run abi.\nexport const sourceAbi = ${JSON.stringify(source.abi)} as const;\nexport const destinationAbi = ${JSON.stringify(destination.abi)} as const;\n`,
);
console.log("Exported cross-chain ABIs");
